/**
 * Generates src/data/europe-map.ts (static SVG paths for the facility map).
 * Not part of the build: run only to change the map extent or detail.
 *
 *   mkdir /tmp/mapgen && cd /tmp/mapgen && npm i d3-geo@3 topojson-client@3 world-atlas@2
 *   cp <repo>/scripts/generate-europe-map.mjs . && node generate-europe-map.mjs > <repo>/src/data/europe-map.ts
 *
 * Projection is plain Mercator, so facility markers are projected at runtime from lat/lng
 * with the scale/translate stored per view (see FacilityMap.tsx).
 * Data: Natural Earth via world-atlas (public domain).
 */
import { readFileSync } from "node:fs";
import { geoMercator, geoPath } from "d3-geo";
import { feature, mesh } from "topojson-client";

const load = (f) => JSON.parse(readFileSync(`node_modules/world-atlas/${f}.json`, "utf8"));


/** Douglas-Peucker on projected points (pixels). */
function rdp(pts, eps) {
  if (pts.length < 3) return pts;
  const first = pts[0], last = pts[pts.length - 1];
  if (first[0] === last[0] && first[1] === last[1]) {
    // Closed ring: split at the point farthest from the start so the chord is not degenerate.
    let f = 1, best = -1;
    for (let k = 1; k < pts.length - 1; k++) {
      const d = Math.hypot(pts[k][0] - first[0], pts[k][1] - first[1]);
      if (d > best) { best = d; f = k; }
    }
    return [...rdp(pts.slice(0, f + 1), eps), ...rdp(pts.slice(f), eps).slice(1)];
  }
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [i, j] = stack.pop();
    const [x1, y1] = pts[i], [x2, y2] = pts[j];
    const dx = x2 - x1, dy = y2 - y1, len = Math.hypot(dx, dy) || 1e-9;
    let max = 0, idx = -1;
    for (let k = i + 1; k < j; k++) {
      const d = Math.abs(dy * pts[k][0] - dx * pts[k][1] + x2 * y1 - y2 * x1) / len;
      if (d > max) { max = d; idx = k; }
    }
    if (max > eps && idx > 0) { keep[idx] = 1; stack.push([i, idx], [idx, j]); }
  }
  return pts.filter((_, i) => keep[i]);
}

function simplifyPath(geo, projection, eps, minSize) {
  const lines = [];
  let cur = null;
  const ctx = {
    moveTo(x, y) { cur = [[x, y]]; lines.push(cur); },
    lineTo(x, y) { cur.push([x, y]); },
    closePath() { if (cur) cur.push(cur[0]); },
    arc() {}, rect() {}, bezierCurveTo() {}, quadraticCurveTo() {},
  };
  geoPath(projection, ctx)(geo);
  const out = [];
  for (const l of lines) {
    const xs = l.map((p) => p[0]), ys = l.map((p) => p[1]);
    if (Math.max(Math.max(...xs) - Math.min(...xs), Math.max(...ys) - Math.min(...ys)) < minSize) continue;
    const r = rdp(l, eps);
    if (r.length < 2) continue;
    // d3's clip adds the frame itself as a ring when a polygon covers it: drop it.
    const onFrame = (p) => p[0] <= -19.9 || p[0] >= projection.__w + 19.9 || p[1] <= -19.9 || p[1] >= projection.__h + 19.9;
    if (r.length <= 6 && r.every(onFrame)) continue;
    out.push("M" + r.map((p) => `${+p[0].toFixed(1)},${+p[1].toFixed(1)}`).join("L"));
  }
  return out.join("");
}

function view({ name, w, h, bounds, res, eps, minSize }) {
  const [west, south, east, north] = bounds;
  const box = { type: "MultiPoint", coordinates: [[west, south], [east, south], [east, north], [west, north]] };
  const projection = geoMercator().fitExtent([[0, 0], [w, h]], box);
  projection.clipExtent([[-20, -20], [w + 20, h + 20]]);
  projection.__w = w;
  projection.__h = h;
  const land = load(`land-${res}`);
  const countries = load(`countries-${res}`);
  const toPath = (geo) => simplifyPath(geo, projection, eps, minSize);
  return {
    name,
    width: w,
    height: h,
    scale: +projection.scale().toFixed(3),
    tx: +projection.translate()[0].toFixed(3),
    ty: +projection.translate()[1].toFixed(3),
    bounds,
    land: toPath(feature(land, land.objects.land)),
    borders: toPath(mesh(countries, countries.objects.countries, (a, b) => a !== b)),
  };
}

const overview = view({ name: "overview", w: 800, h: 600, bounds: [-11, 34, 34, 62], res: "50m", eps: 0.6, minSize: 2 });
const detail = view({ name: "detail", w: 640, h: 720, bounds: [3.5, 46.0, 12.5, 54.6], res: "10m", eps: 0.5, minSize: 2 });

